// src/lib/keyyoWebhook.ts
//
// Keyyo "Notification d'appels" (API serveur): Keyyo calls a URL of ours for every event of a
// Keyyo line. Pure parsing here — no database, no request — so the rules can be read and tested
// on their own; src/app/api/keyyo/webhook/route.ts applies them.
//
// Reference: Keyyo "Guide d'utilisation CTI / API / TAPI" v1.6 and
// https://www.keyyo.com/fr/telephonie-api/notification-appels — the URL is set per line in the
// Keyyo Manager (Configurer > Paramètres avancés > CTI > API serveur), called by HTTP GET from
// Keyyo (source IP 83.136.160.79), and contains keywords Keyyo replaces on each notification.
// The URL we hand out (KEYYO_URL_PARAMS) names them:
//   account=_ACCOUNT_       the Keyyo line, international form         -> the adviser's line
//   caller=_CALLER_         the calling number (= account: outgoing)    -> the customer
//   callee=_CALLEE_         the called number (= account: incoming)
//   callref=_CALLREF_       the call (one per line that rings)
//   type=_N_TYPE_           SETUP (initiation), CONNECT (connexion), RELEASE (fin)
//   session=_SESSION_ID_    common to every call generated by ONE incoming call on a numéro
//                           d'accueil (standard): the lines it rang share it
//   acd=_IS_ACD_            1 when the call comes from a numéro d'accueil
//   redirecting=_REDIRECTING_NUMBER_  the line forwarding the call, on a forwarded call
//   tsms=_TSMS_             timestamp of the event, in milliseconds     -> start / end times
//   dref=_DREF_             the dialogue (differs from the callref)
//   drefreplace=_DREF_REPLACE_  on an interception (supervision) or an attended transfer: the
//                           _DREF_ of the dialogue taken over. In that new dialogue the line that
//                           takes the call is the CALLER and the customer the CALLEE.
//   version=_N_VERSION_
// When voicemail answers, the answering number is far longer than a phone number (22 digits):
// that CONNECT is not an adviser answering.
//
// The names of the Keyyo call export are accepted too ("Début d'appel", "Numéro appelant",
// "Numéro présenté", "Numéro appelé"), with the import's meaning: présenté = the customer, appelé
// = the adviser's line, appelant = the standard line. Names are compared without case, accents
// or separators; a keyword Keyyo left unreplaced (_SESSION_ID_…) counts as empty.
import { normalizePhone } from "@/lib/phone";

/** Query string to append to our webhook URL in the Keyyo Manager. */
export const KEYYO_URL_PARAMS =
  "account=_ACCOUNT_&caller=_CALLER_&callee=_CALLEE_&callref=_CALLREF_&type=_N_TYPE_" +
  "&session=_SESSION_ID_&acd=_IS_ACD_&redirecting=_REDIRECTING_NUMBER_&tsms=_TSMS_" +
  "&dref=_DREF_&drefreplace=_DREF_REPLACE_&version=_N_VERSION_";

export type KeyyoEventType = "ringing" | "answered" | "ended" | "unknown";
export type KeyyoDirection = "incoming" | "outgoing" | "unknown";

export type KeyyoNotification = {
  type: KeyyoEventType;
  /** Keyyo's word for it, as received (SETUP, CONNECT…). */
  rawType: string;
  /** Per Keyyo's rule: callee = line -> incoming, caller = line -> outgoing. */
  direction: KeyyoDirection;
  /** Identifier of this line's call; null if Keyyo sent none. */
  callRef: string | null;
  /** Identifier shared by the lines one standard call rang; null outside a numéro d'accueil. */
  sessionId: string | null;
  /** The call comes from a numéro d'accueil (standard). */
  isAcd: boolean;
  /** The customer's number (caller / Numéro présenté), national form. */
  customer: string;
  /** Numbers that may be the adviser's line, most specific first (account, Numéro appelé, callee). */
  adviserCandidates: string[];
  /** Numbers that may be the standard line it came in on (Numéro appelant, redirecting, callee). */
  lineCandidates: string[];
  /** Start of the call when given ("Début d'appel"); otherwise null (= now). */
  startedAt: Date | null;
  /** Time of this event (_TSMS_), Paris wall-clock like startedAt; null if not sent (= now). */
  eventAt: Date | null;
  /** Duration in seconds when given. */
  durationSeconds: number | null;
  dref: string | null;
  /** _DREF_REPLACE_: the dialogue this one takes over (interception, attended transfer). */
  drefReplace: string | null;
  /** The line itself (account), national form. */
  account: string;
  /** The other party when the line is the CALLER (interception): the customer of the taken call. */
  callee: string;
  /** A CONNECT answered by voicemail (22-digit answering number), not by the adviser. */
  voicemail: boolean;
  /**
   * Who handled the call when the source names a USER rather than a line (Ringover): an
   * AssurPilot user id already known for it, else the email / name to look the adviser up by.
   */
  adviserHint?: { userId?: string | null; email?: string | null; firstname?: string | null; lastname?: string | null; fullName?: string | null };
  /** Source of the notification, kept in the call's rawMeta ("ringover"); Keyyo when absent. */
  provider?: "ringover";
  /** Agency of the standard line the call came from: the adviser of that agency is preferred. */
  preferAgency?: "CPA" | "ALM" | null;
  /** Route Keyyo standard -> Ringover, kept in the call's rawMeta (see CallTrace in keyyoCalls). */
  trace?: {
    standardLine?: string | null; standardLabel?: string | null; agency?: string | null;
    ringoverNumber?: string | null; ringoverAgent?: string | null;
  };
};

function key(name: string): string {
  return name.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "");
}

function pick(params: Map<string, string>, ...names: string[]): string {
  for (const n of names) {
    const v = params.get(key(n));
    // "_SESSION_ID_" left as is: Keyyo had no value for that keyword.
    if (v !== undefined && v.trim() !== "" && !/^_[A-Z_]+_$/.test(v.trim())) return v.trim();
  }
  return "";
}

const TYPE_WORDS: Array<[KeyyoEventType, RegExp]> = [
  ["ringing", /^(setup|ring|ringing|sonnerie|incoming|alerting|start|debut|nouveau|new)$/],
  ["answered", /^(connect|connected|answer|answered|decroche|decroch|pickup|up|bridge)$/],
  ["ended", /^(release|released|hangup|hang_up|end|ended|fin|raccroche|disconnect|terminated)$/],
];

export function eventType(raw: string): KeyyoEventType {
  const w = key(raw);
  for (const [type, re] of TYPE_WORDS) if (re.test(w)) return type;
  return "unknown";
}

/**
 * Date and time as the rest of the application stores them: the Paris wall-clock time put in a
 * UTC Date (that is what the Excel import does with Keyyo's "Début d'appel", so a call keeps the
 * same instant whichever way it arrived). A text without a zone is taken as Paris time; an epoch
 * or a zoned ISO date is converted to Paris time first.
 */
export function parisWallClock(input: Date | string | number | null | undefined, now: Date = new Date()): Date {
  const fromInstant = (d: Date) => {
    const parts = new Intl.DateTimeFormat("en-GB", {
      timeZone: "Europe/Paris", hourCycle: "h23",
      year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit",
    }).formatToParts(d);
    const get = (t: string) => Number(parts.find((p) => p.type === t)!.value);
    return new Date(Date.UTC(get("year"), get("month") - 1, get("day"), get("hour"), get("minute"), get("second")));
  };
  if (input === null || input === undefined || input === "") return fromInstant(now);
  if (input instanceof Date) return fromInstant(input);
  const text = String(input).trim();
  if (/^\d{10}(\.\d+)?$/.test(text)) return fromInstant(new Date(Number(text) * 1000));
  if (/^\d{13}$/.test(text)) return fromInstant(new Date(Number(text)));
  let m = text.match(/^(\d{2})\/(\d{2})\/(\d{4})[ T](\d{1,2}):(\d{2})(?::(\d{2}))?$/);
  if (m) return new Date(Date.UTC(+m[3], +m[2] - 1, +m[1], +m[4], +m[5], +(m[6] ?? 0)));
  m = text.match(/^(\d{4})-(\d{2})-(\d{2})[ T](\d{1,2}):(\d{2})(?::(\d{2}))?$/);
  if (m) return new Date(Date.UTC(+m[1], +m[2] - 1, +m[3], +m[4], +m[5], +(m[6] ?? 0)));
  const parsed = new Date(text);
  return Number.isNaN(parsed.getTime()) ? fromInstant(now) : fromInstant(parsed);
}

/** Reads one notification from its parameters (query string, form or JSON, merged). */
export function parseKeyyoNotification(raw: Record<string, unknown>): KeyyoNotification {
  const params = new Map<string, string>();
  for (const [k, v] of Object.entries(raw)) {
    if (v === null || v === undefined || typeof v === "object") continue;
    params.set(key(k), String(v));
  }

  const rawType = pick(params, "type", "n_type", "event", "evenement", "etat", "state", "status", "statut");
  const account = normalizePhone(pick(params, "account", "compte", "ligne"));
  const caller = normalizePhone(pick(params, "caller", "callerid", "cli", "from"));
  const callee = normalizePhone(pick(params, "callee", "called", "to"));
  const appele = pick(params, "Numéro appelé", "numero_appele");
  const appelant = pick(params, "Numéro appelant", "numero_appelant");
  const redirecting = pick(params, "redirecting", "redirecting_number", "renvoi");
  const customer = normalizePhone(pick(params, "Numéro présenté", "numero_presente")) || caller;
  const start = pick(params, "Début d'appel", "debut_appel", "debut", "date", "start", "starttime", "datetime", "timestamp");
  const duration = pick(params, "Durée réelle", "duree", "duration");
  const tsms = pick(params, "tsms", "_tsms_", "event_time");
  const rawCallee = pick(params, "callee", "called", "to").replace(/\D/g, "");

  // Keyyo's own rule (only meaningful when it sent the line).
  const direction: KeyyoDirection = !account ? "unknown" : caller && caller === account ? "outgoing" : callee && callee === account ? "incoming" : "unknown";
  const acd = pick(params, "acd", "is_acd");

  const uniq = (xs: string[]) => [...new Set(xs.map((x) => normalizePhone(x)).filter(Boolean))];
  return {
    type: rawType ? eventType(rawType) : "unknown",
    rawType,
    direction,
    callRef: pick(params, "callref", "call_ref", "callid", "call_id", "id_appel", "uniqueid") || null,
    sessionId: pick(params, "session", "session_id", "sessionid") || null,
    isAcd: acd === "1" || /^(true|oui|yes)$/i.test(acd),
    customer,
    adviserCandidates: uniq([account, appele, callee]),
    lineCandidates: uniq([appelant, redirecting, callee]),
    startedAt: start ? parisWallClock(start) : null,
    eventAt: /^\d{10,13}$/.test(tsms) ? parisWallClock(tsms) : null,
    durationSeconds: duration && /^\d+$/.test(duration) ? Number(duration) : null,
    dref: pick(params, "dref") || null,
    drefReplace: pick(params, "drefreplace", "dref_replace") || null,
    account,
    callee,
    // Keyyo: a call answered by voicemail shows an answering number of 22 digits.
    voicemail: rawType ? eventType(rawType) === "answered" && rawCallee.length >= 20 : false,
  };
}
