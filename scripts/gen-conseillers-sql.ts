// scripts/gen-conseillers-sql.ts
//
// Generates prisma/sql/008-conseillers-lignes.sql from prisma/data/conseillers-lignes.json
// (the list of advisers and their direct lines, names exactly as supplied).
//
//   npx tsx scripts/gen-conseillers-sql.ts
//
// Lines are written in the national form the file import compares against
// (normalizePhone: +33374470362 / 33374470362 / 374470362 -> 0374470362), so an
// adviser's "Numéro appelé" in a Keyyo export finds them whatever the spelling.
import fs from "node:fs";
import path from "node:path";
import { normalizePhone } from "../src/lib/phone";

type Row = { prenom: string; nom: string; ligne: string };
const root = path.join(__dirname, "..");
const rows: Row[] = JSON.parse(fs.readFileSync(path.join(root, "prisma/data/conseillers-lignes.json"), "utf8"));

const data = rows.map((r, i) => {
  const ligne = normalizePhone(r.ligne);
  if (!/^0\d{9}$/.test(ligne)) throw new Error(`Ligne invalide pour ${r.prenom} ${r.nom}: ${r.ligne}`);
  return { ordre: i + 1, prenom: r.prenom, nom: r.nom, ligne };
});
const json = JSON.stringify(data, null, 1);
const jsonLine = JSON.stringify(data);
if (json.includes("$json$")) throw new Error("delimiter clash");

const shared = new Map<string, string[]>();
for (const d of data) shared.set(d.ligne, [...(shared.get(d.ligne) ?? []), `${d.prenom} ${d.nom}`.trim()]);
const sharedNote = [...shared].filter(([, w]) => w.length > 1).map(([l, w]) => `--     ${l} : ${w.join("  /  ")}`).join("\n");

const ACCENTS_FROM = "àâäáãéèêëíìîïóòôöõúùûüçñ";
const ACCENTS_TO = "aaaaaeeeeiiiiooooouuuucn";
const fold = (x: string) =>
  `regexp_replace(translate(lower(btrim(${x})), '${ACCENTS_FROM}', '${ACCENTS_TO}'), '\\s+', ' ', 'g')`;

const sql = `-- prisma/sql/008-conseillers-lignes.sql
--
-- GENERATED by scripts/gen-conseillers-sql.ts from prisma/data/conseillers-lignes.json
-- (${data.length} conseillers). Edit the JSON and regenerate; do not edit this file by hand.
--
-- Sets each conseiller's DIRECT LINE (users."phoneNumber") and the exact spelling of
-- their prénom / nom. The line is what a Keyyo import matches on ("Numéro appelé"),
-- written in the national form the import compares (0XXXXXXXXX).
--
--   * A conseiller is recognised by name — case, accents and prénom/nom order ignored —
--     among the existing users. Found (exactly one, role CONSEILLER): line, prénom and nom
--     are updated; nothing else (team, coach, password, active flag) is touched.
--   * Not found: created as an ACTIVE CONSEILLER with no team and no coach, email
--     prenom.nom@assurpilot.fr and a password nobody can log in with. An administrator
--     must give them a team, a coach and a password (Utilisateurs). Set
--     v_creer_manquants to false below to only update existing users.
--   * Ambiguous (several users with that name) or a different role: skipped, and shown
--     in the result table at the end.
--   * Users who are not in the list are left exactly as they are.
--
-- Safe to run more than once: the second run changes nothing.
--
-- LINES GIVEN TO TWO PEOPLE in the supplied list (both are applied as supplied, but an
-- import can attribute the call to only one of them — check which is right):
${sharedNote || "--     (none)"}

DO $$
DECLARE
  v_creer_manquants constant boolean := true;
  v_data jsonb := $json$
${json}
$json$::jsonb;
  e record;
  n int;
  uid text;
  urole text;
  v_email text;
  v_rows int;
BEGIN
  FOR e IN SELECT * FROM jsonb_to_recordset(v_data) AS x(ordre int, prenom text, nom text, ligne text) ORDER BY ordre LOOP
    SELECT count(*), min(id), min(role) INTO n, uid, urole
    FROM users
    WHERE ${fold('prenom || \' \' || nom')} IN (${fold('e.prenom || \' \' || e.nom')}, ${fold('e.nom || \' \' || e.prenom')});

    IF n = 1 AND urole = 'CONSEILLER' THEN
      UPDATE users SET "phoneNumber" = e.ligne, prenom = e.prenom, nom = e.nom
      WHERE id = uid AND ("phoneNumber" IS DISTINCT FROM e.ligne OR prenom IS DISTINCT FROM e.prenom OR nom IS DISTINCT FROM e.nom);
      GET DIAGNOSTICS v_rows = ROW_COUNT;
      IF v_rows > 0 THEN RAISE NOTICE '% % : mis à jour (ligne %)', e.prenom, e.nom, e.ligne; END IF;
    ELSIF n = 1 THEN
      RAISE NOTICE '% % : ignoré, cet utilisateur a le rôle %', e.prenom, e.nom, urole;
    ELSIF n > 1 THEN
      RAISE NOTICE '% % : ignoré, % utilisateurs portent ce nom', e.prenom, e.nom, n;
    ELSIF v_creer_manquants THEN
      v_email := regexp_replace(regexp_replace(translate(lower(btrim(e.prenom || '.' || e.nom)), '${ACCENTS_FROM}', '${ACCENTS_TO}'), '[^a-z0-9]+', '.', 'g'), '(^\\.+|\\.+$)', '', 'g') || '@assurpilot.fr';
      INSERT INTO users (id, email, password, nom, prenom, "phoneNumber", role, "isActive")
      VALUES ('c' || substr(md5(random()::text || clock_timestamp()::text || e.ordre::text), 1, 24), v_email,
              '!inutilisable!' || md5(random()::text || clock_timestamp()::text), e.nom, e.prenom, e.ligne, 'CONSEILLER', true)
      ON CONFLICT (email) DO NOTHING;
      GET DIAGNOSTICS v_rows = ROW_COUNT;
      IF v_rows > 0 THEN RAISE NOTICE '% % : créé (%)', e.prenom, e.nom, v_email;
      ELSE RAISE NOTICE '% % : NON créé, l''e-mail % existe déjà', e.prenom, e.nom, v_email; END IF;
    END IF;
  END LOOP;
END $$;

-- Result: one row per conseiller of the list (single line on purpose: some SQL editors cut
-- multi-line statements). statut = OK when the user exists with exactly this prénom, nom and
-- line; anything else needs a look (see the comments above).
SELECT e.ordre, e.prenom, e.nom, e.ligne, CASE WHEN u.id IS NULL THEN 'ABSENT (non trouvé / non créé / ambigu)' WHEN u.role <> 'CONSEILLER' THEN 'IGNORÉ : rôle ' || u.role WHEN u.prenom = e.prenom AND u.nom = e.nom AND u."phoneNumber" = e.ligne THEN 'OK' ELSE 'À VÉRIFIER' END AS statut, u.email, u."isActive" AS actif, t.nom AS equipe, (SELECT count(*) FROM users s WHERE s."phoneNumber" = e.ligne) AS utilisateurs_sur_cette_ligne FROM jsonb_to_recordset($json$${jsonLine}$json$::jsonb) AS e(ordre int, prenom text, nom text, ligne text) LEFT JOIN users u ON ${fold('u.prenom || \' \' || u.nom')} IN (${fold('e.prenom || \' \' || e.nom')}, ${fold('e.nom || \' \' || e.prenom')}) LEFT JOIN teams t ON t.id = u."teamId" ORDER BY e.ordre;
`;
fs.writeFileSync(path.join(root, "prisma/sql/008-conseillers-lignes.sql"), sql);
console.log(`prisma/sql/008-conseillers-lignes.sql written (${data.length} conseillers)`);
